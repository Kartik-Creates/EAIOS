# ── generate_tool_response() ─────────────────────────────────────────
#
# No retry loop lives here anymore — it used to, but that stacked on top of
# _generate_gemini_completion()'s own retry-with-a-fallback-model behavior
# (tested above), multiplying a single failure into up to 4 real API calls
# instead of 2. Resilience now lives in exactly one place; these tests just
# confirm this function is a plain, honest pass-through to it.


@pytest.mark.asyncio
async def test_generate_tool_response_returns_completion_result(monkeypatch):
    """Plain pass-through: whatever generate_completion() returns is what
    the caller gets, with no extra attempts at this level."""
    calls = {"count": 0}

    async def mock_completion(prompt: str) -> str:
        calls["count"] += 1
        return "Here is your synthesized answer."

    monkeypatch.setattr("app.services.llm_service.generate_completion", mock_completion)

    result = await generate_tool_response("What's my latest email?", "[GMAIL DATA] ...")
    assert result == "Here is your synthesized answer."
    assert calls["count"] == 1


@pytest.mark.asyncio
async def test_generate_tool_response_propagates_failure_without_retrying(monkeypatch):
    """If generate_completion() fails, generate_tool_response() raises
    immediately — it must NOT retry at this level too, since
    _generate_gemini_completion() one level down already tried a fallback
    model before this exception ever surfaced. The caller (chat.py) is
    responsible for falling back to something safe from here."""
    calls = {"count": 0}

    async def always_fails(prompt: str) -> str:
        calls["count"] += 1
        raise RuntimeError("simulated failure, already retried one level down")

    monkeypatch.setattr("app.services.llm_service.generate_completion", always_fails)

    with pytest.raises(RuntimeError, match="simulated failure"):
        await generate_tool_response("What's my latest email?", "[GMAIL DATA] ...")
    assert calls["count"] == 1
