"""Unit tests for the swappable LLM provider abstraction (Ollama vs Gemini API)."""
from unittest.mock import MagicMock

import pytest

from app.core.config import settings
from app.services.llm_service import LLMServiceError, generate_completion


@pytest.mark.asyncio
async def test_generate_completion_ollama_path(monkeypatch):
    """When LLM_PROVIDER='ollama', generate_completion routes to Ollama API."""
    monkeypatch.setattr(settings, "LLM_PROVIDER", "ollama")

    class MockResponse:
        def raise_for_status(self):
            pass

        def json(self):
            return {"response": "Answer from Ollama local model."}

    async def mock_post(self, url, *args, **kwargs):
        return MockResponse()

    monkeypatch.setattr("httpx.AsyncClient.post", mock_post)

    res = await generate_completion("What is our leave policy?")
    assert res == "Answer from Ollama local model."


@pytest.mark.asyncio
async def test_generate_completion_gemini_path(monkeypatch):
    """When LLM_PROVIDER='gemini', generate_completion routes to Google Gemini API."""
    monkeypatch.setattr(settings, "LLM_PROVIDER", "gemini")
    monkeypatch.setattr(settings, "GEMINI_API_KEY", "test-gemini-key")
    monkeypatch.setattr(settings, "GEMINI_MODEL", "gemini-2.5-flash")

    mock_model_instance = MagicMock()
    mock_model_response = MagicMock()
    mock_model_response.text = "Answer generated by Gemini 2.5 Flash API."
    mock_model_instance.generate_content.return_value = mock_model_response

    mock_genai = MagicMock()
    mock_genai.GenerativeModel.return_value = mock_model_instance

    monkeypatch.setattr("google.generativeai.configure", mock_genai.configure)
    monkeypatch.setattr("google.generativeai.GenerativeModel", mock_genai.GenerativeModel)

    res = await generate_completion("What is our leave policy?")
    assert res == "Answer generated by Gemini 2.5 Flash API."

    # Verify Gemini configuration and model creation
    mock_genai.configure.assert_called_once_with(api_key="test-gemini-key")
    mock_genai.GenerativeModel.assert_called_once_with("gemini-2.5-flash")
    mock_model_instance.generate_content.assert_called_once()


@pytest.mark.asyncio
async def test_generate_completion_gemini_missing_key_raises_error(monkeypatch):
    """When LLM_PROVIDER='gemini' but GEMINI_API_KEY is empty, a clean LLMServiceError is raised."""
    monkeypatch.setattr(settings, "LLM_PROVIDER", "gemini")
    monkeypatch.setattr(settings, "GEMINI_API_KEY", "")

    with pytest.raises(LLMServiceError) as exc_info:
        await generate_completion("Test prompt")

    assert "GEMINI_API_KEY is not configured" in str(exc_info.value)


@pytest.mark.asyncio
async def test_generate_completion_invalid_provider_raises_error(monkeypatch):
    """When LLM_PROVIDER is invalid, LLMServiceError is raised."""
    monkeypatch.setattr(settings, "LLM_PROVIDER", "invalid_provider")

    with pytest.raises(LLMServiceError) as exc_info:
        await generate_completion("Test prompt")

    assert "Unsupported LLM_PROVIDER" in str(exc_info.value)
